'use strict';
// Fetch only public, official documentation for detected frameworks. No project text is uploaded.
const fs = require('fs');
const path = require('path');
const https = require('https');
const { spawnSync } = require('child_process');

const DOCS = {
  react: 'https://react.dev/learn', next: 'https://nextjs.org/docs', vue: 'https://vuejs.org/guide/introduction.html',
  svelte: 'https://svelte.dev/docs/svelte/overview', express: 'https://expressjs.com/en/starter/installing.html',
  fastify: 'https://fastify.dev/docs/latest/', typescript: 'https://www.typescriptlang.org/docs/',
  django: 'https://docs.djangoproject.com/en/stable/', flask: 'https://flask.palletsprojects.com/en/stable/',
  pytest: 'https://docs.pytest.org/en/stable/', go: 'https://go.dev/doc/', rust: 'https://doc.rust-lang.org/book/',
};
const clean = s => String(s).replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&[^;]+;/g, ' ').replace(/[\r\n|`\[\]]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 120);
function detect(dir) {
  let pkg = {};
  try { pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')); } catch (_) { /* other stacks */ }
  const deps = { ...pkg.dependencies, ...pkg.devDependencies };
  const found = Object.keys(DOCS).filter(k => deps[k] || (k === 'typescript' && fs.existsSync(path.join(dir, 'tsconfig.json'))));
  const req = ['requirements.txt', 'pyproject.toml'].map(f => { try { return fs.readFileSync(path.join(dir, f), 'utf8'); } catch (_) { return ''; } }).join('\n');
  for (const k of ['django', 'flask', 'pytest']) if (new RegExp(`\\b${k}\\b`, 'i').test(req) && !found.includes(k)) found.push(k);
  if (fs.existsSync(path.join(dir, 'go.mod'))) found.push('go');
  if (fs.existsSync(path.join(dir, 'Cargo.toml'))) found.push('rust');
  return found.slice(0, 4).map(name => ({ name, url: DOCS[name] }));
}
function curlTitle(url) {
  const r = spawnSync('curl', ['--location', '--silent', '--show-error', '--max-time', '6', '--max-filesize', '524288', '--proto-redir', '=https', url],
    { encoding: 'utf8', timeout: 7000, maxBuffer: 600000, windowsHide: true });
  return r.status === 0 ? clean(/<title[^>]*>([\s\S]*?)<\/title>/i.exec(r.stdout || '')?.[1] || '') : null;
}
function directTitle(url) {
  return new Promise(resolve => {
    let settled = false;
    const done = x => { if (!settled) { settled = true; resolve(x); } };
    const req = https.get(url, { headers: { 'User-Agent': 'AskAI project-init/1.2', Accept: 'text/html' }, timeout: 2500 }, res => {
      if (res.statusCode !== 200 || !String(res.headers['content-type'] || '').includes('text/html')) { res.resume(); return done(null); }
      let body = '';
      res.on('data', chunk => { body += chunk; if (body.length > 128000) { req.destroy(); done(null); } });
      res.on('end', () => done(clean(/<title[^>]*>([\s\S]*?)<\/title>/i.exec(body)?.[1] || '')));
      res.on('error', () => done(null));
    });
    req.on('timeout', () => { req.destroy(); done(null); });
    req.on('error', () => done(null));
  });
}
async function fetchTitle(url) {
  if (process.env.HTTPS_PROXY || process.env.HTTP_PROXY) return curlTitle(url);
  return (await directTitle(url)) || curlTitle(url);
}
async function collect(dir, o = {}) {
  const docs = detect(dir);
  const cache = path.join(dir, '.ai-work', 'official-research.json');
  let old = {};
  try { old = JSON.parse(fs.readFileSync(cache, 'utf8')); } catch (_) { /* fresh */ }
  const now = Date.now();
  const rows = [];
  for (const d of docs) {
    const prior = old[d.name];
    if (prior && prior.title && prior.url === d.url && now - prior.at < 7 * 86400000) { rows.push({ ...d, title: prior.title, status: 'checked' }); continue; }
    if (o.offline || o.dry) { rows.push({ ...d, title: '', status: 'offline' }); continue; }
    const title = await (o.fetchTitle || fetchTitle)(d.url);
    rows.push({ ...d, title: clean(title || ''), status: title ? 'checked' : 'unavailable' });
  }
  if (!o.offline && !o.dry && rows.length) {
    fs.mkdirSync(path.dirname(cache), { recursive: true });
    fs.writeFileSync(cache, JSON.stringify(Object.fromEntries(rows.filter(r => r.title).map(r => [r.name, { url: r.url, title: r.title, at: now }])), null, 2));
  }
  return rows;
}
function markdown(rows) {
  return ['<!-- askai:generated by `askai init`; official documentation links only. -->', '# Official references', '',
    'Selected from detected manifests. AskAI fetches page titles only, keeps a seven-day local cache, and sends no repository content. Read a relevant page when changing that framework; do not load all references each session.', '',
    '| Stack | Official documentation | Lookup |', '| --- | --- | --- |',
    ...(rows.length ? rows.map(r => `| ${r.name} | [${clean(r.title) || r.name}](${r.url}) | ${r.status} |`) : ['| — | No recognized framework manifest | no lookup |']), ''].join('\n');
}
module.exports = { detect, collect, markdown };

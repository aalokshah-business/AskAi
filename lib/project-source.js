'use strict';
// One-time, local source inventory. Never send repository contents to a service.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const SOURCE = /\.(?:[cm]?[jt]sx?|py|go|rs|kt|java|swift|php|dart|vue|svelte|cs|c|cc|cpp|h|rb|sql|html|css|scss|ino)$/i;
const PRIVATE = /(^|\/)(?:\.env(?:\.|$)|id_rsa|id_ed25519|[^/]+\.(?:pem|key|p12|pfx)$)/i;
const MAX_BYTES = 1024 * 1024;
const MAX_EDGES = 16;
const normal = s => s.replace(/\\/g, '/');
const esc = s => String(s).replace(/[`|<>[\]]/g, '').replace(/[\r\n]+/g, ' ').trim();
const group = f => f.includes('/') ? f.split('/')[0] : '(root)';

function inspect(dir, files) {
  const sources = files.filter(f => SOURCE.test(f) && !PRIVATE.test(normal(f))).map(normal);
  const known = new Set(sources);
  const rows = []; const edges = new Map(); const routes = [];
  const fileHashes = {};
  let skipped = 0; const skippedFiles = [];
  for (const rel of sources) {
    const file = path.join(dir, rel);
    let body;
    try {
      const stat = fs.statSync(file);
      if (stat.size > MAX_BYTES) { skipped++; skippedFiles.push(rel); continue; }
      body = fs.readFileSync(file, 'utf8');
      if (body.includes('\0')) { skipped++; skippedFiles.push(rel); continue; }
    } catch (_) { skipped++; skippedFiles.push(rel); continue; }
    fileHashes[rel] = crypto.createHash('sha256').update(body).digest('hex');
    const symbols = [];
    for (const m of body.matchAll(/(?:^|\n)\s*(?:export\s+(?:default\s+)?|public\s+|async\s+)*(?:function|class|interface|type|def|struct|enum)\s+([A-Za-z_$][\w$]*)/g)) {
      if (!symbols.includes(m[1])) symbols.push(m[1]);
      if (symbols.length === 4) break;
    }
    for (const m of body.matchAll(/(?:\bfrom\s*|\brequire\s*\(\s*|\bimport\s*\(\s*|\bimport\s*)['"](\.{1,2}\/[^'"]+)['"]/g)) {
      const target = path.posix.normalize(path.posix.join(path.posix.dirname(rel), m[1]));
      const resolved = [target, ...['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs', '.py', '.vue', '.svelte', '/index.ts', '/index.js'].map(x => target + x)].find(x => known.has(x));
      if (resolved && group(resolved) !== group(rel)) {
        const key = `${group(rel)}\0${group(resolved)}`;
        if (!edges.has(key)) edges.set(key, rel);
      }
    }
    for (const m of body.matchAll(/\b(?:app|router|server)\s*\.\s*(get|post|put|patch|delete)\s*\(\s*['"`]([^'"`\n]+)['"`]/g)) {
      if (routes.length < 30) routes.push({ method: m[1].toUpperCase(), route: m[2], file: rel });
    }
    rows.push({ file: rel, group: group(rel), symbols });
  }
  return { eligible: sources.length, scanned: rows.length, skipped, skippedFiles, rows, fileHashes,
    edges: [...edges].slice(0, MAX_EDGES).map(([key, file]) => ({ from: key.split('\0')[0], to: key.split('\0')[1], file })), routes };
}

function index(info) {
  const scan = info.source;
  const counts = new Map();
  for (const r of scan.rows) counts.set(r.group, (counts.get(r.group) || 0) + 1);
  const groups = [...counts].sort((a, b) => b[1] - a[1]).slice(0, 12).map(([name, n]) => `| \`${name}\` | ${n} |`);
  return ['<!-- askai:generated by `askai init`; read a matching row, not this whole file. -->',
    '# Source index', '',
    `Scanned ${scan.scanned}/${scan.eligible} eligible first-party source files; ${scan.skipped} unreadable, binary or over 1 MiB.${scan.truncated ? ' Discovery stopped at 20,000 files; split the repository or inspect remaining source manually.' : ''} Dependencies, build output and private files excluded. Static inventory, not runtime verification.`, '',
    'Search for a path or symbol, then read that source range. Paste a row into a session, not this file.', '',
    '## Folders', '| Folder | Source files scanned |', '| --- | --- |', ...(groups.length ? groups : ['| — | 0 |']), '',
    '## Files', '| File | Top-level declarations |', '| --- | --- |',
    ...scan.rows.map(r => `| \`${r.file}\` | ${r.symbols.map(esc).join(', ') || '—'} |`),
    ...(scan.skippedFiles.length ? ['', '## Skipped source files', ...scan.skippedFiles.map(f => `- \`${f}\``)] : []), ''].join('\n');
}

module.exports = { inspect, index };
